namespace Boxes.Models;

/// <summary>
/// Visual style/theme for a Box container
/// </summary>
public enum BoxStyle
{
    /// <summary>
    /// Standard Windows Mica material (default)
    /// </summary>
    Windows,

    /// <summary>
    /// Clear acetate-like glass with subtle tint (acetate glasses frames vibe)
    /// </summary>
    Acetate,

    /// <summary>
    /// Solid color with no transparency
    /// </summary>
    Solid,

    /// <summary>
    /// Desktop acrylic blur effect
    /// </summary>
    Acrylic,

    /// <summary>
    /// Minimal thin border, mostly transparent
    /// </summary>
    Minimal,

    /// <summary>
    /// Frosted glass effect
    /// </summary>
    Frosted
}
